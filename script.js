class mathFunctions {

     constructor(a,b) {
     this.a = a
     this.b = b
     }


     add()  {
          return this.a +  this.b;
     }

     subtract()  {
          return this.a - this.b;
     }

     multiply()  {
          return this.a * this.b;
     }

     divide()  {
          return this.a / this.b;
     }
}

let iwkms = new mathFunctions(666, 333);

console.log(iwkms.add(), iwkms.subtract(), iwkms.multiply(), iwkms.divide());   

